// A single-quoted JavaScript string literal for a title such as "Who's singing".
export const jsString = (s) => {
	const backslash = String.fromCharCode(92);
	const body = String(s)
		.split(backslash)
		.join(backslash + backslash)
		.split("'")
		.join(backslash + "'")
		.replace(/[\r\n]+/g, ' ');
	return `'${body}'`;
};
